"""Build ocr_eval/datasets/synthetic_7seg: rendered 7-segment displays.

A control set, not a measure of real-world accuracy: digits drawn by
tests/synthetic_images.seven_segment, coloured as a lit LED display (bright
segments on dark) or a reflective LCD (dark segments on light), slightly blurred
and noisy. Deterministic (fixed seed).

    python -m ocr_eval.builders.synthetic_7seg [--out FOLDER]
"""

import argparse
import shutil
import sys
from pathlib import Path

import numpy as np

from ocr_eval import DATASETS_DIR, REPO_ROOT
from ocr_eval.builders._common import write_png, write_text
from ocr_eval.dataset import Sample, assign_split, write_manifest

NAME = "synthetic_7seg"
SEED = 7
SCORES = [
    "0",
    "3",
    "7",
    "9",
    "12",
    "21",
    "45",
    "58",
    "88",
    "99",
    "105",
    "118",
    "147",
    "199",
]
CLOCKS = [
    "12:34",
    "0:59",
    "9:07",
    "15:00",
    "1:45",
    "20:00",
    "9.5",
    "45.1",
    "3.8",
    "0.4",
]
PERIODS = ["1", "2", "3", "4"]
# (display_tech, background BGR, segment BGR)
STYLES = [
    ("led7", (18, 18, 18), (40, 40, 235)),  # red LED
    ("led7", (12, 14, 16), (30, 170, 250)),  # amber LED
    ("led7", (25, 20, 20), (235, 235, 235)),  # white LED
    ("lcd", (170, 190, 178), (45, 50, 45)),  # reflective LCD
]
HEIGHTS = [28, 40, 56]

LICENSE_TEXT = """\
The images and labels in this folder were generated by
ocr_eval/builders/synthetic_7seg.py and are dedicated to the public domain
under CC0 1.0 Universal (https://creativecommons.org/publicdomain/zero/1.0/).
"""

ATTRIBUTION_TEXT = """\
# Attribution

No attribution required: every image in this dataset is synthetic, rendered by
`ocr_eval/builders/synthetic_7seg.py` with `tests/synthetic_images.py`
(CC0-1.0).
"""

README_TEXT = """\
# synthetic_7seg

Rendered 7-segment LED and LCD digits (scores, clocks, periods): a synthetic control set, not a measure of real-world accuracy.

Built by `python -m ocr_eval.builders.synthetic_7seg` (deterministic). Each crop is a
display rendered by `tests/synthetic_images.seven_segment`, coloured as a lit LED (red,
amber or white segments on black) or a reflective LCD (dark segments on grey-green),
then lightly blurred and given Gaussian noise. Licensed CC0-1.0.
"""


def render(text: str, style, height: int, rng: np.random.Generator) -> np.ndarray:
    import cv2

    sys.path.insert(0, str(REPO_ROOT / "tests"))
    try:
        from synthetic_images import seven_segment
    finally:
        sys.path.remove(str(REPO_ROOT / "tests"))

    _, background, segment = style
    mask = seven_segment(text, height=height, pad=max(8, height // 4)) > 127
    image = np.empty(mask.shape + (3,), np.float32)
    image[:] = background
    image[mask] = segment
    image = cv2.GaussianBlur(image, (3, 3), 0)
    image += rng.normal(0.0, 4.0, image.shape)
    return np.clip(image, 0, 255).astype(np.uint8)


def build(out: Path) -> list[Sample]:
    rng = np.random.default_rng(SEED)
    # start over (only the images folder: --out may hold other files)
    shutil.rmtree(out / "images", ignore_errors=True)
    samples = []
    values = (
        [(v, "score") for v in SCORES]
        + [(v, "clock") for v in CLOCKS]
        + [(v, "period") for v in PERIODS]
    )
    for value, field_type in values:
        # two renderings per value, in different styles and sizes
        for style_index in rng.choice(len(STYLES), size=2, replace=False):
            style = STYLES[int(style_index)]
            height = HEIGHTS[int(rng.integers(len(HEIGHTS)))]
            slug = value.replace(":", "c").replace(".", "d")
            sample_id = f"syn7_{field_type}_{slug}_{style_index}_{height}"
            image = f"images/{sample_id}.png"
            write_png(out / image, render(value, style, height, rng))
            samples.append(
                Sample(
                    id=sample_id,
                    image=image,
                    text=value,
                    field_type=field_type,
                    display_tech=style[0],
                    split=assign_split(sample_id),
                    label_source="synthetic",
                    license="CC0-1.0",
                    source_url=None,
                    author="ScoreSight contributors",
                    attribution="Generated by ocr_eval/builders/synthetic_7seg.py (CC0-1.0)",
                    source_box=None,
                    notes=f"{height} px digits",
                )
            )
    write_manifest(out, samples)
    write_text(out / "LICENSE", LICENSE_TEXT)
    write_text(out / "ATTRIBUTION.md", ATTRIBUTION_TEXT)
    write_text(out / "README.md", README_TEXT)
    return samples


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=DATASETS_DIR / NAME)
    args = parser.parse_args(argv)
    samples = build(args.out)
    print(f"Wrote {len(samples)} crops to {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
